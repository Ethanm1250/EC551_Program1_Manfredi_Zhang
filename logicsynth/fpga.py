SEG7_SOURCE = """\
// Multiplexed hexadecimal 7-segment driver (active-low segments and anodes,
// as on Digilent Basys 3 / Nexys A7).  Each digit is lit for 2**17 clock
// cycles (~1.3 ms at 100 MHz), fast enough to look continuously on.
module seg7_hex #(
    parameter DIGITS = 4
) (
    input  wire                  clk,
    input  wire [4*DIGITS-1:0]   value,     // hex digits, digit 0 = rightmost
    input  wire [DIGITS-1:0]     enable,    // 1 = show digit
    output reg  [6:0]            seg,       // {g,f,e,d,c,b,a}, active low
    output reg  [DIGITS-1:0]     an         // active low
);
    localparam SEL_BITS = (DIGITS > 4) ? 3 : 2;
    reg [16+SEL_BITS:0] refresh = 0;
    wire [SEL_BITS-1:0] sel = refresh[16+SEL_BITS -: SEL_BITS];
    wire [3:0] nibble = value[4*sel +: 4];

    always @(posedge clk) refresh <= refresh + 1'b1;

    always @(*) begin
        an = {DIGITS{1'b1}};
        if (sel < DIGITS && enable[sel]) an[sel] = 1'b0;
        case (nibble)                  //  gfedcba (active high, inverted below)
            4'h0: seg = ~7'b0111111;
            4'h1: seg = ~7'b0000110;
            4'h2: seg = ~7'b1011011;
            4'h3: seg = ~7'b1001111;
            4'h4: seg = ~7'b1100110;
            4'h5: seg = ~7'b1101101;
            4'h6: seg = ~7'b1111101;
            4'h7: seg = ~7'b0000111;
            4'h8: seg = ~7'b1111111;
            4'h9: seg = ~7'b1101111;
            4'hA: seg = ~7'b1110111;
            4'hB: seg = ~7'b1111100;
            4'hC: seg = ~7'b0111001;
            4'hD: seg = ~7'b1011110;
            4'hE: seg = ~7'b1111001;
            default: seg = ~7'b1110001;  // F
        endcase
    end
endmodule
"""


def _wrapper(nl, board):
    b = BOARDS[board]
    n = len(nl.inputs)
    digits = len(b["an"])
    sources = ["sw[%d]" % k for k in range(16)] + list(b["btn"])   # x[0], x[1], ...
    hex_digits = min(digits, (min(n, 16) + 3) // 4) or 1
    lines = [
        "// Board wrapper generated by logicsynth: maps FPGA I/O onto the generated logic.",
        f"// Board: {board}.  Switches = inputs (sw[0] = LSB of the minterm index),",
        "// LEDs = outputs, 7-segment display = current minterm index in hex.",
        "module top (",
        "    input  wire        clk,",
        "    input  wire [15:0] sw,",
        "    input  wire        " + ", ".join(b["btn"]) + ",",
        "    output wire [15:0] led,",
        "    output wire [6:0]  seg,",
        "    output wire        dp,",
        f"    output wire [{digits - 1}:0]  an",
        ");",
        f"    // x[k] is bit k of the minterm index; design input i uses x[{n - 1}-i]",
        f"    wire [{max(n, 1) - 1}:0] x;",
    ]
    for k in range(n):
        src = sources[k] if k < len(sources) else "1'b0   /* not enough board inputs */"
        lines.append(f"    assign x[{k}] = {src};")
    out_wires = [f"y{k}" for k in range(len(nl.outputs))]
    lines.append(f"    wire {', '.join(out_wires)};" if out_wires else "")
    conns = [f".{name}(x[{n - 1 - i}])" for i, name in enumerate(nl.inputs)]
    conns += [f".{o}({w})" for o, w in zip(nl.outputs, out_wires)]
    lines.append(f"    {nl.module} u_logic (")
    lines.append("        " + ",\n        ".join(conns))
    lines.append("    );")
    used_leds = min(len(out_wires), 16)
    led_bits = [out_wires[k] if k < used_leds else "1'b0" for k in range(15, -1, -1)]
    lines.append(f"    assign led = {{{', '.join(led_bits)}}};")
    lines.append("    assign dp  = 1'b1;   // decimal points off")
    in_bits = min(n, 16)
    if in_bits == 0:
        value = f"{4 * digits}'d0"
    elif in_bits < 4 * digits:
        value = f"{{{4 * digits - in_bits}'d0, sw[{in_bits - 1}:0]}}"
    else:
        value = f"sw[{4 * digits - 1}:0]"
    enable = "{" + ", ".join("1'b1" if d < hex_digits else "1'b0" for d in range(digits - 1, -1, -1)) + "}"
    lines += [
        f"    seg7_hex #(.DIGITS({digits})) u_seg (",
        f"        .clk(clk), .value({value}), .enable({enable}),",
        "        .seg(seg), .an(an)",
        "    );",
        "endmodule",
    ]
    return "\n".join(lines) + "\n"


def _xdc(board):
    b = BOARDS[board]

    def pin(p, port, std="LVCMOS33"):
        return f"set_property -dict {{ PACKAGE_PIN {p} IOSTANDARD {std} }} [get_ports {{{port}}}]"

    lines = [f"## Pin constraints for {board} generated by logicsynth",
             "## (verify against the Digilent master XDC for your board)", "",
             pin(b["clk"], "clk"),
             "create_clock -add -name sys_clk_pin -period 10.00 -waveform {0 5} [get_ports {clk}]", ""]
    lines += [pin(p, f"sw[{k}]", b["sw_std"].get(k, "LVCMOS33")) for k, p in enumerate(b["sw"])]
    lines.append("")
    lines += [pin(p, f"led[{k}]") for k, p in enumerate(b["led"])]
    lines.append("")
    lines += [pin(p, name) for name, p in b["btn"].items()]
    lines.append("")
    lines += [pin(p, f"seg[{k}]") for k, p in enumerate(b["seg"])]
    lines.append(pin(b["dp"], "dp"))
    lines += [pin(p, f"an[{k}]") for k, p in enumerate(b["an"])]
    lines += ["", "set_property CFGBVS VCCO [current_design]",
              "set_property CONFIG_VOLTAGE 3.3 [current_design]"]
    return "\n".join(lines) + "\n"


def _build_tcl(nl, board):
    b = BOARDS[board]
    return f"""\
# Non-interactive Vivado build:   vivado -mode batch -source build.tcl
# Produces top.bit plus utilization / timing reports in this directory.
set dir [file dirname [info script]]
read_verilog [list $dir/{nl.module}.v $dir/seg7_hex.v $dir/top.v]
read_xdc $dir/{board}.xdc
synth_design -top top -part {b['part']}
opt_design
place_design
route_design
report_utilization    -file $dir/utilization.rpt
report_timing_summary -file $dir/timing.rpt
write_bitstream -force $dir/top.bit
"""


PROGRAM_TCL = """\
# Program the board over USB:   vivado -mode batch -source program.tcl
set dir [file dirname [info script]]
open_hw_manager
connect_hw_server
open_hw_target
set dev [lindex [get_hw_devices xc7a*] 0]
current_hw_device $dev
set_property PROGRAM.FILE $dir/top.bit $dev
program_hw_devices $dev
close_hw_manager
"""


def generate_project(outdir, nl, design, verilog_text, board="basys3"):
    if board not in BOARDS:
        raise ValueError(f"unknown board '{board}' (choose: {', '.join(BOARDS)})")
    os.makedirs(os.path.join(outdir, "sim"), exist_ok=True)
    files = {
        f"{nl.module}.v": verilog_text,
        "top.v": _wrapper(nl, board),
        "seg7_hex.v": SEG7_SOURCE,
        f"{board}.xdc": _xdc(board),
        "build.tcl": _build_tcl(nl, board),
        "program.tcl": PROGRAM_TCL,
    }
    tb = emit_testbench(nl, design)
    if tb:
        files[os.path.join("sim", f"tb_{nl.module}.v")] = tb
    written = []
    for rel, text in files.items():
        path = os.path.join(outdir, rel)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        written.append(path)
    notes = []
    if len(nl.inputs) > 21:
        notes.append(f"{len(nl.inputs) - 21} input(s) tied to 0 (only 16 switches + 5 buttons)")
    if len(nl.outputs) > 16:
        notes.append(f"only the first 16 of {len(nl.outputs)} outputs drive LEDs")
    return written, notes
